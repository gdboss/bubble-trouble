/**
 * Design token helpers: read a W3C DTCG-style token file, validate it,
 * and turn it into CSS custom properties for styles/styles.css.
 * Pure functions only, so every rule here is covered by unit tests.
 */

export const START_MARKER = '/* design-tokens:start - generated by `npm run tokens:build`, do not edit by hand */';
export const END_MARKER = '/* design-tokens:end */';
const DISABLE = '/* stylelint-disable color-no-hex -- tokens are the only place for literal colors */';
const ENABLE = '/* stylelint-enable color-no-hex */';

const NAME_PATTERN = /^[a-z0-9][a-z0-9-]*$/;
const ALIAS_PATTERN = /^\{([a-z0-9.-]+)\}$/;
const HEX_PATTERN = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i;
const DIMENSION_PATTERN = /^(0|-?(\d+|\d*\.\d+)(px|rem|em))$/;
const SUPPORTED_TYPES = ['color', 'dimension'];

/**
 * Walks the token tree and returns a Map of "group.name" -> { type, value }.
 * $type is inherited from the closest parent group, as in the DTCG format.
 */
export function flattenTokens(tree, prefix = [], inheritedType = undefined, out = new Map()) {
  const groupType = tree.$type ?? inheritedType;
  Object.entries(tree).forEach(([key, node]) => {
    if (key.startsWith('$')) return;
    if (!NAME_PATTERN.test(key)) {
      throw new Error(`Invalid token name "${[...prefix, key].join('.')}": use lowercase letters, digits and hyphens`);
    }
    const path = [...prefix, key];
    if (node === null || typeof node !== 'object') {
      throw new Error(`Token "${path.join('.')}" must be an object with a $value`);
    }
    if ('$value' in node) {
      const type = node.$type ?? groupType;
      if (!SUPPORTED_TYPES.includes(type)) {
        throw new Error(`Token "${path.join('.')}" has unsupported $type "${type}" (supported: ${SUPPORTED_TYPES.join(', ')})`);
      }
      out.set(path.join('.'), { type, value: String(node.$value).trim() });
    } else {
      flattenTokens(node, path, groupType, out);
    }
  });
  return out;
}

export function aliasTarget(value) {
  const match = ALIAS_PATTERN.exec(value);
  return match ? match[1] : null;
}

/** Follows aliases until a literal value is found. Detects missing targets and loops. */
export function resolveToken(name, tokens, seen = []) {
  if (seen.includes(name)) {
    throw new Error(`Alias loop: ${[...seen, name].join(' -> ')}`);
  }
  const token = tokens.get(name);
  if (!token) {
    const from = seen.length ? ` (referenced by "${seen[seen.length - 1]}")` : '';
    throw new Error(`Unknown token "${name}"${from}`);
  }
  const target = aliasTarget(token.value);
  if (!target) return token.value;
  const targetToken = tokens.get(target);
  if (targetToken && targetToken.type !== token.type) {
    throw new Error(`Token "${name}" (${token.type}) points to "${target}" (${targetToken.type})`);
  }
  return resolveToken(target, tokens, [...seen, name]);
}

/** Checks every token: aliases resolve, colors are hex, dimensions have a unit. */
export function validateTokens(tokens) {
  const errors = [];
  tokens.forEach((token, name) => {
    try {
      const value = resolveToken(name, tokens);
      if (token.type === 'color' && !HEX_PATTERN.test(value)) {
        errors.push(`Token "${name}": "${value}" is not a #rgb or #rrggbb color`);
      }
      if (token.type === 'dimension' && !DIMENSION_PATTERN.test(value)) {
        errors.push(`Token "${name}": "${value}" is not a px, rem or em value`);
      }
    } catch (e) {
      errors.push(e.message);
    }
  });
  if (errors.length) {
    throw new Error(`Invalid design tokens:\n  - ${errors.join('\n  - ')}`);
  }
}

/** #aabbcc -> #abc, as stylelint's color-hex-length rule expects. */
export function shortHex(hex) {
  const h = hex.toLowerCase();
  return /^#([0-9a-f])\1([0-9a-f])\2([0-9a-f])\3$/.test(h) ? `#${h[1]}${h[3]}${h[5]}` : h;
}

export const cssVarName = (name) => `--${name.replace(/\./g, '-')}`;

/**
 * Aliases stay aliases in CSS (var(--x)), so changing a primitive
 * updates everything that uses it.
 */
export function buildCssLines(tokens) {
  validateTokens(tokens);
  const lines = [];
  tokens.forEach((token, name) => {
    const target = aliasTarget(token.value);
    let value = token.value.toLowerCase();
    if (target) value = `var(${cssVarName(target)})`;
    else if (token.type === 'color') value = shortHex(value);
    lines.push(`${cssVarName(name)}: ${value};`);
  });
  return lines;
}

/** Replaces everything between the two markers. The markers must already exist. */
export function replaceRegion(css, lines) {
  const start = css.indexOf(START_MARKER);
  const end = css.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start || css.indexOf(START_MARKER, start + 1) !== -1) {
    throw new Error(
      'styles/styles.css needs exactly one pair of design token markers inside the first :root block:\n'
      + `  ${START_MARKER}\n  ${END_MARKER}`,
    );
  }
  const lineStart = css.lastIndexOf('\n', start) + 1;
  const indent = css.slice(lineStart, start);
  const body = [DISABLE, ...lines, ENABLE].map((line) => `${indent}${line}`).join('\n');
  // Blank line before the end marker keeps stylelint's comment-empty-line-before rule happy.
  return `${css.slice(0, start)}${START_MARKER}\n${body}\n\n${indent}${css.slice(end)}`;
}

/** Returns the generated region (between the markers) so other checks can skip it. */
export function regionBounds(css) {
  const start = css.indexOf(START_MARKER);
  const end = css.indexOf(END_MARKER);
  return start === -1 || end === -1 ? null : { start, end: end + END_MARKER.length };
}
